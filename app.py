def generate_with_openai(prompt, project_name, api_key, model):
    if OpenAI is None:
        raise RuntimeError("OpenAI package missing. Install requirements.txt.")
    client = OpenAI(api_key=api_key)
    system = '''You are IF, an experienced Python and Streamlit coding agent. Return ONLY valid JSON: {"summary":"...","files":[{"path":"app.py","content":"..."},{"path":"requirements.txt","content":"..."},{"path":"README.md","content":"..."}]}. Generate a focused, runnable Python + Streamlit project. Include setup instructions. Maximum 12 files, each under 30000 characters. Never include secrets, credentials, destructive code, or absolute paths. Do not claim you ran code. Include app.py, requirements.txt, README.md and any necessary helpers.'''
    response = client.chat.completions.create(
        model=model,
        temperature=0.2,
        response_format={"type": "json_object"},
        messages=[{"role": "system", "content": system}, {"role": "user", "content": f"Project name: {project_name}\nIdea:\n{prompt}"}],
    )
    data = json.loads(response.choices[0].message.content or "{}")
    files = {}
    for item in data.get("files", [])[:12]:
        path = safe_path(item.get("path"))
        content = str(item.get("content", ""))
        if path and len(content) <= 30000:
            files[path] = content
    if "app.py" not in files:
        raise ValueError("The model did not return app.py. Try a more specific prompt.")
    files.setdefault("requirements.txt", "streamlit>=1.36.0\n")
    files.setdefault("README.md", f"# {project_name}\n\nGenerated by IF — INTELLIGENCE FACTORY.\n")
    files.setdefault(".streamlit/config.toml", '[theme]\nbase = "dark"\nprimaryColor = "#60A5FA"\nbackgroundColor = "#07111F"\nsecondaryBackgroundColor = "#0B1930"\ntextColor = "#E7EFFF"\n')
    return data.get("summary", "AI-generated project."), files


def build_zip(files, project_name):
    buffer = io.BytesIO()
    root = safe_project_name(project_name)
    with zipfile.ZipFile(buffer, "w", zipfile.ZIP_DEFLATED) as zf:
        for path, content in files.items():
            path = safe_path(path)
            if path:
                zf.writestr(f"{root}/{path}", content)
    return buffer.getvalue()


def check_syntax(files):
    passed, errors = [], []
    for path, content in files.items():
        if path.endswith(".py"):
            try:
                compile(content, path, "exec")
                passed.append(path)
            except SyntaxError as exc:
                errors.append(f"{path}: line {exc.lineno}: {exc.msg}")
    return passed, errors


