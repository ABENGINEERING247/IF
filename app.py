def safe_project_name(name):
    return (re.sub(r"[^a-zA-Z0-9_-]+", "_", (name or "").strip()).strip("_") or "generated_project")[:48]


def safe_path(path):
    path = str(path or "").replace("\\", "/").strip().lstrip("/")
    parts = [p for p in path.split("/") if p not in ("", ".", "..")]
    cleaned = "/".join(parts)
    return cleaned if cleaned and len(cleaned) <= 180 else ""


