def generate_with_luna_openai(prompt, project_name, api_key, model):
    if OpenAI is None:
        raise RuntimeError(
            "OpenAI package missing. Please install `openai` via requirements."
        )

    client = OpenAI(api_key=api_key)

    # GPT-6 Luna System Persona Prompt
    system_luna = (
        "You are Luna, an advanced GPT-6 Python and Streamlit coding assistant"
        " for IF (INTELLIGENCE FACTORY). "
        "You craft fast, clean, high-performance Python projects. Return ONLY"
        ' valid JSON in this structure: {"summary":"...","files":[{"path":"app.py","content":"..."},{"path":"requirements.txt","content":"..."},{"path":"README.md","content":"..."}]}. '
        "Generate a complete, fully functional Python + Streamlit project based"
        " on the idea. Maximum 12 files, each under 30000 characters. "
        "Never include secrets, credentials, destructive code, or absolute"
        " paths. "
        "Always ensure app.py, requirements.txt, and README.md are included."
    )

    response = client.chat.completions.create(
        model=model,
        temperature=1.0,  # Temperature set to 1.0 as requested
        response_format={"type": "json_object"},
        messages=[
            {"role": "system", "content": system_luna},
            {
                "role": "user",
                "content": f"Project name: {project_name}\nIdea:\n{prompt}",
            },
        ],
    )

    data = json.loads(response.choices[0].message.content or "{}")
    files = {}

    for item in data.get("files", [])[:12]:
        path = safe_path(item.get("path"))
        content = str(item.get("content", ""))
        if path and len(content) <= 30000:
            files[path] = content

    if "app.py" not in files:
        raise ValueError(
            "GPT-6 Luna was unable to generate app.py. Please refine your prompt."
        )

    files.setdefault("requirements.txt", "streamlit>=1.36.0\n")
    files.setdefault(
        "README.md",
        f"# {project_name}\n\nGenerated by IF — INTELLIGENCE FACTORY"
        " (GPT-6 Luna AI).\n",
    )
    files.setdefault(
        ".streamlit/config.toml",
        '[theme]\nbase = "light"\nprimaryColor = "#D97706"\nbackgroundColor ='
        ' "#F8FAFC"\nsecondaryBackgroundColor = "#F1F5F9"\ntextColor ='
        ' "#0F172A"\n',
    )

    return (
        data.get("summary", "AI project generated successfully by GPT-6 Luna."),
        files,
    )


def build_zip(files, project_name):
    buffer = io.BytesIO()
    root = safe_project_name(project_name)
    with zipfile.ZipFile(buffer, "w", zipfile.ZIP_DEFLATED) as zf:
        for path, content in files.items():
            path = safe_path(path)
            if path:
                zf.writestr(f"{root}/{path}", content)
    return buffer.getvalue()


def check_syntax(files):
    passed, errors = [], []
    for path, content in files.items():
        if path.endswith(".py"):
            try:
                compile(content, path, "exec")
                passed.append(path)
            except SyntaxError as exc:
                errors.append(f"{path}: line {exc.lineno}: {exc.msg}")
    return passed, errors


